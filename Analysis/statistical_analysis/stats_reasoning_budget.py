"""
Within-family paired tests for the effect of reasoning budget.

Section 5.3 of the paper claims things like "+1.5 points from low to high"
without any significance test. Because each family member is run on the SAME
1,010 questions, we can use paired McNemar / Wilcoxon to ask: are the gains
from increased reasoning budget statistically reliable?

Families compared (defined in stats_core.REASONING_FAMILIES):
  * GPT-5         : low vs high
  * Gemini 2.5 Pro: 8K vs 16K vs 32K
  * Grok 3 Mini   : low vs high
  * DeepSeek      : 8K vs 16K vs 32K
  * Claude Opus 4.6 : high vs max

For 3-member families we test 8K vs 16K, 16K vs 32K, and 8K vs 32K, with
Holm correction within the family. We report on (a) overall benchmark and
(b) binary-only McNemar.
"""
from __future__ import annotations

import itertools
from pathlib import Path

import numpy as np
import pandas as pd

from stats_core import (
    MULTIANSWER_CATS,
    REASONING_FAMILIES,
    auto_paired_test,
    holm_bonferroni,
    load_all_scores,
    stars,
    task_unweighted_mean,
)

OUT_DIR = Path(__file__).resolve().parent / "stats_outputs"
OUT_DIR.mkdir(exist_ok=True)


def main() -> None:
    scores, meta = load_all_scores()
    cats = meta["question_category"].astype(str).str.lower().values
    binary_mask = ~np.isin(cats, list(MULTIANSWER_CATS))

    rows = []
    for family, members in REASONING_FAMILIES.items():
        present = [m for m in members if m in scores]
        if len(present) < 2:
            continue

        pairs = list(itertools.combinations(present, 2))
        raw_p_overall = []
        raw_p_binary = []
        records = []
        for a, b in pairs:
            sa_o = scores[a]["name"]
            sb_o = scores[b]["name"]
            sa_b = sa_o[binary_mask]
            sb_b = sb_o[binary_mask]
            r_o = auto_paired_test(sa_o, sb_o)
            r_b = auto_paired_test(sa_b, sb_b)
            raw_p_overall.append(r_o["p_value"])
            raw_p_binary.append(r_b["p_value"])
            records.append({
                "family": family,
                "model_a": a,
                "model_b": b,
                # task-unweighted means (matches Table 3 / Section 5.3 wording)
                "mean_a_uw_pct": 100 * task_unweighted_mean(sa_o, cats),
                "mean_b_uw_pct": 100 * task_unweighted_mean(sb_o, cats),
                # question-weighted means (over 1,010 vector) for transparency
                "mean_a_qw_pct": 100 * sa_o.mean(),
                "mean_b_qw_pct": 100 * sb_o.mean(),
                # Overall (Wilcoxon, mixed)
                "diff_overall_pp_qw": 100 * r_o["mean_diff"],
                "diff_uw_pp": (100 * task_unweighted_mean(sa_o, cats)) -
                              (100 * task_unweighted_mean(sb_o, cats)),
                "ci_overall_lo": 100 * r_o["ci_lo"],
                "ci_overall_hi": 100 * r_o["ci_hi"],
                "p_overall_raw": r_o["p_value"],
                "test_overall": r_o["test"],
                "d_overall": r_o["cohens_d"],
                # Binary-only (McNemar)
                "diff_binary_pp": 100 * r_b["mean_diff"],
                "ci_binary_lo": 100 * r_b["ci_lo"],
                "ci_binary_hi": 100 * r_b["ci_hi"],
                "p_binary_raw": r_b["p_value"],
                "test_binary": r_b["test"],
                "d_binary": r_b["cohens_d"],
            })
        adj_o = holm_bonferroni(raw_p_overall)
        adj_b = holm_bonferroni(raw_p_binary)
        for rec, po, pb in zip(records, adj_o, adj_b):
            rec["p_overall_holm"] = po
            rec["p_binary_holm"] = pb
        rows.extend(records)

    df = pd.DataFrame(rows)
    out_csv = OUT_DIR / "reasoning_budget_paired_tests.csv"
    df.to_csv(out_csv, index=False)
    print(f"[written] {out_csv}")

    # ---- LaTeX snippet ----
    # Compress comparison labels by stripping the shared family-name prefix.
    # E.g. "Deepseek_8K vs Deepseek_16K" -> "8K vs 16K" — the Family column
    # already captures the family.
    def _short_pair(a: str, b: str) -> str:
        i = 0
        while i < len(a) and i < len(b) and a[i] == b[i]:
            i += 1
        # back up to underscore boundary so we don't slice mid-token
        while i > 0 and a[i - 1] != "_":
            i -= 1
        sa = a[i:].replace("_", " ").strip()
        sb = b[i:].replace("_", " ").strip()
        return f"{sa} vs {sb}"

    tex_path = OUT_DIR / "reasoning_budget_table.tex"
    with tex_path.open("w") as fh:
        fh.write("% Auto-generated by stats_reasoning_budget.py — do not edit by hand.\n")
        fh.write("\\begin{table}[t]\n\\centering\\scriptsize\n")
        fh.write("\\setlength{\\tabcolsep}{4pt}\n")
        fh.write("\\caption{Effect of reasoning budget within each model family. "
                 "Each comparison is paired across the 1,010 benchmark questions. "
                 "$\\Delta$ overall is from the Wilcoxon signed-rank test on mixed binary+F1 "
                 "scores; $\\Delta$ binary is from McNemar's exact test on the 830 single-answer "
                 "questions, with 95\\% Clopper--Pearson CI. $p$-values are Holm--Bonferroni "
                 "corrected within each family. Compound-name prompts.}\n")
        fh.write("\\label{tab:reasoning_budget}\n")
        fh.write("\\begin{tabular}{llccccc}\n\\toprule\n")
        fh.write("Family & Comparison & $\\Delta_\\text{overall}$ & Wilcoxon $p$ & "
                 "$\\Delta_\\text{binary}$ [95\\% CI] & McNemar $p$ & $d$ \\\\\n\\midrule\n")
        for _, r in df.iterrows():
            short = _short_pair(r["model_a"], r["model_b"])
            fh.write(
                f"{r['family']} & "
                f"{short} & "
                f"{r['diff_uw_pp']:+.2f} & "
                f"{r['p_overall_holm']:.2g}{stars(r['p_overall_holm'])} & "
                f"{r['diff_binary_pp']:+.2f} {{\\tiny[{r['ci_binary_lo']:+.1f},{r['ci_binary_hi']:+.1f}]}} & "
                f"{r['p_binary_holm']:.2g}{stars(r['p_binary_holm'])} & "
                f"{r['d_binary']:+.2f} \\\\\n"
            )
        fh.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    print(f"[written] {tex_path}")

    print("\nReasoning budget paired tests (Holm-corrected within family):")
    show = df[[
        "family", "model_a", "model_b",
        "diff_uw_pp", "p_overall_holm",
        "diff_binary_pp", "p_binary_holm", "d_binary",
    ]].copy()
    print(show.to_string(index=False, float_format=lambda x: f"{x:.3g}"))


if __name__ == "__main__":
    main()
