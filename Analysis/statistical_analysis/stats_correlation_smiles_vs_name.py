"""
Steiger's Z for the SMILES-vs-Name continuous-rating Pearson correlation gap.

Section 5.4 of the paper claims (Figure 3a): for OIn / OPl / OS the SMILES
and Name prompts produce "similar correlations across all three dimensions,
with a slightly larger gap for OIn." This script attaches a formal test:

For each (model, task), compute
    r_NH  = corr(name_pred,   human_truth)
    r_SH  = corr(smiles_pred, human_truth)
    r_NS  = corr(name_pred,   smiles_pred)   # measured on the same items

then test H0: r_NH == r_SH using **Steiger's Z** for two dependent
correlations sharing one variable (here the human ratings). p-values are
Holm--Bonferroni corrected across models within each task.

Output: per-(model, task) row with both correlations, Fisher-z 95% CIs,
Steiger Z, raw p, Holm p; LaTeX summary; console table.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from stats_core import (
    DATA_DIR,
    PATTERN,
    extract_numeric_ratings_per_task,
    holm_bonferroni,
    pearson_r_with_ci,
    stars,
    steiger_z_test,
    model_name_from_path,
)

OUT_DIR = Path(__file__).resolve().parent / "stats_outputs"
OUT_DIR.mkdir(exist_ok=True)


def main() -> None:
    files = sorted(DATA_DIR.glob(PATTERN))
    rows = []

    for fp in files:
        try:
            df = pd.read_csv(fp, dtype=str, keep_default_na=True)
        except Exception as e:
            print(f"[skip] {fp.name}: {e}")
            continue
        if "other_info" not in df.columns:
            continue

        model = model_name_from_path(fp)

        # Per-task numeric ratings, separately for the two prompt formats
        nm = extract_numeric_ratings_per_task(df, "answer_to_prompt_2")  # name
        sm = extract_numeric_ratings_per_task(df, "answer_to_prompt_1")  # smiles

        for cat in ["odor_intensity", "odor_pleasantness", "mixture_similarity"]:
            p_nm, t_nm = nm[cat]
            p_sm, t_sm = sm[cat]

            # The "shared" variable for Steiger is the human ratings. We need
            # all three pairs aligned per question×stimulus, so we recompute
            # the per-item arrays from the full df keeping NaNs.
            mask_cat = df["question_category"].astype(str).str.lower().values == cat
            sub = df[mask_cat].reset_index(drop=True)
            p_nm_all, t_all_n = _per_item(sub, "answer_to_prompt_2", cat)
            p_sm_all, t_all_s = _per_item(sub, "answer_to_prompt_1", cat)

            # alignment check — should be identical truth arrays
            assert len(t_all_n) == len(t_all_s)
            valid = (~np.isnan(p_nm_all) & ~np.isnan(p_sm_all)
                     & ~np.isnan(t_all_n) & ~np.isnan(t_all_s))
            if valid.sum() < 4:
                continue
            p_nm_v = p_nm_all[valid]
            p_sm_v = p_sm_all[valid]
            t_v = t_all_n[valid]

            r_NH, lo_NH, hi_NH, _ = pearson_r_with_ci(p_nm_v, t_v)
            r_SH, lo_SH, hi_SH, _ = pearson_r_with_ci(p_sm_v, t_v)
            r_NS, _, _, _ = pearson_r_with_ci(p_nm_v, p_sm_v)
            n = int(valid.sum())
            z, p_steiger = steiger_z_test(r_NH, r_SH, r_NS, n)

            rows.append({
                "model": model,
                "task": {"odor_intensity": "OIn",
                          "odor_pleasantness": "OPl",
                          "mixture_similarity": "OS"}[cat],
                "n_items": n,
                "r_name_human": r_NH,
                "name_lo": lo_NH,
                "name_hi": hi_NH,
                "r_smiles_human": r_SH,
                "smiles_lo": lo_SH,
                "smiles_hi": hi_SH,
                "r_name_smiles": r_NS,
                "diff": r_NH - r_SH,
                "steiger_z": z,
                "p_steiger": p_steiger,
            })

    df = pd.DataFrame(rows)

    # Holm correction within each task across models
    for task in ["OIn", "OPl", "OS"]:
        sub_idx = df.index[df["task"] == task].tolist()
        if not sub_idx:
            continue
        adj = holm_bonferroni(df.loc[sub_idx, "p_steiger"].tolist())
        for idx, p_h in zip(sub_idx, adj):
            df.at[idx, "p_steiger_holm"] = p_h

    out_csv = OUT_DIR / "correlation_smiles_vs_name_steiger.csv"
    df.to_csv(out_csv, index=False)
    print(f"[written] {out_csv}")

    # ---- LaTeX summary table (one row per (model, task), only top 8 by name r per task) ----
    tex_path = OUT_DIR / "correlation_smiles_vs_name_table.tex"
    with tex_path.open("w") as fh:
        fh.write("% Auto-generated by stats_correlation_smiles_vs_name.py\n")
        fh.write("\\begin{table}[t]\n\\centering\\small\n")
        fh.write("\\caption{Steiger's Z test on the SMILES vs.\\ compound-name "
                 "Pearson correlation gap for the continuous-rating tasks "
                 "(intensity, pleasantness, mixture similarity). Both correlations "
                 "share the same human ratings, so they are dependent and tested "
                 "via Steiger's Z (1980) on the difference of two correlations "
                 "sharing one variable. $p$-values are Holm--Bonferroni corrected "
                 "across all evaluated models within each task. "
                 "\\textsuperscript{***}$p<0.001$, \\textsuperscript{**}$p<0.01$, "
                 "\\textsuperscript{*}$p<0.05$.}\n")
        fh.write("\\label{tab:steiger_smiles_vs_name}\n")
        fh.write("\\begin{tabular}{llcccccc}\n\\toprule\n")
        fh.write("Task & Model & $r$ Name & $r$ SMILES & "
                 "$\\Delta r$ & $r_{NS}$ & Steiger $Z$ & Holm $p$ \\\\\n\\midrule\n")
        for task in ["OIn", "OPl", "OS"]:
            sub = df[df["task"] == task].sort_values("r_name_human", ascending=False)
            for _, r in sub.iterrows():
                if pd.isna(r.get("p_steiger_holm")):
                    continue
                fh.write(
                    f"{task} & {r['model'].replace('_', ' ')} & "
                    f"{r['r_name_human']:+.3f} & {r['r_smiles_human']:+.3f} & "
                    f"{r['diff']:+.3f} & {r['r_name_smiles']:+.3f} & "
                    f"{r['steiger_z']:+.2f} & "
                    f"{r['p_steiger_holm']:.2g}{stars(r['p_steiger_holm'])} \\\\\n"
                )
            fh.write("\\midrule\n")
        fh.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    print(f"[written] {tex_path}")

    # ---- Console summary ----
    print("\nSteiger Z, SMILES-vs-Name correlation gap (Holm-corrected within task):")
    print("-" * 92)
    for task in ["OIn", "OPl", "OS"]:
        sub = df[df["task"] == task].sort_values("r_name_human", ascending=False)
        if sub.empty:
            continue
        print(f"\n[{task}]  n_items median={int(sub['n_items'].median())}")
        for _, r in sub.iterrows():
            sig = stars(r.get("p_steiger_holm", float("nan")))
            print(f"  {r['model']:<24s} "
                  f"r_N={r['r_name_human']:+.3f}  "
                  f"r_S={r['r_smiles_human']:+.3f}  "
                  f"Δr={r['diff']:+.3f}  "
                  f"Z={r['steiger_z']:+.2f}  "
                  f"p_holm={r.get('p_steiger_holm', float('nan')):.2g} {sig}")


def _per_item(sub: pd.DataFrame, pred_col: str, cat: str) -> tuple[np.ndarray, np.ndarray]:
    """Return (pred, truth) per-item arrays preserving NaN rows."""
    from stats_core import (_extract_two_ratings, _extract_one_rating,
                             _truth_numerics_oin_opl, _truth_numeric_os)
    n = len(sub)
    pred = np.full(n * 2, np.nan)
    truth = np.full(n * 2, np.nan)
    for i in range(n):
        oi = sub.iloc[i].get("other_info")
        if cat in {"odor_intensity", "odor_pleasantness"}:
            p1, p2 = _extract_two_ratings(sub.iloc[i][pred_col])
            t1, t2 = _truth_numerics_oin_opl(oi)
            pred[2 * i] = p1
            pred[2 * i + 1] = p2
            truth[2 * i] = t1
            truth[2 * i + 1] = t2
        elif cat == "mixture_similarity":
            pred[2 * i] = _extract_one_rating(sub.iloc[i][pred_col])
            truth[2 * i] = _truth_numeric_os(oi)
    return pred, truth


if __name__ == "__main__":
    main()
